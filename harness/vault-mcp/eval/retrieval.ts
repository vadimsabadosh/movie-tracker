// `npm run eval`: retrieval quality of search_notes before (keyword) and after (semantic) PR7.
// Runs every question of docs/rag-evaluation/questions.json through both modes and checks
// whether the notes that hold the answer come back in the top 5 distinct notes.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createSemanticIndex, createVault } from '../src/config.ts';
import type { SearchHit } from '../src/vault.ts';

const K = 5;
const DOCS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../docs/rag-evaluation');

interface Question {
  id: string;
  kind: string;
  question: string;
  expected: string[];
}

interface Row {
  id: string;
  top: string[];
  /** Rank (1-based) of the first expected note, 0 if none in the top K. */
  firstHit: number;
  recall: number;
}

const questions = JSON.parse(await readFile(path.join(DOCS, 'questions.json'), 'utf8')) as Question[];
const index = createSemanticIndex();
const vault = createVault(index);
await vault.assertReady();
const notes = await vault.listNotes();

// Called directly rather than through vault.search, so a semantic failure is not hidden by the keyword fallback.
const modes: Record<string, (q: string) => Promise<SearchHit[]>> = {
  keyword: (q) => vault.keywordSearch(q, { limit: 50 }),
  semantic: (q) => index.search(notes, q, { limit: 50 }),
};

const results: Record<string, Row[]> = {};
for (const [mode, search] of Object.entries(modes)) {
  results[mode] = [];
  for (const q of questions) {
    const top = [...new Set((await search(q.question)).map((h) => h.title))].slice(0, K);
    const ranks = q.expected.map((title) => top.indexOf(title) + 1);
    const found = ranks.filter((r) => r > 0);
    results[mode].push({
      id: q.id,
      top,
      firstHit: found.length ? Math.min(...found) : 0,
      recall: round(found.length / q.expected.length),
    });
  }
}

const summary = (rows: Row[]) => ({
  hitAt1: rows.filter((r) => r.firstHit === 1).length,
  hitAtK: rows.filter((r) => r.firstHit > 0).length,
  meanRecallAtK: round(rows.reduce((s, r) => s + r.recall, 0) / rows.length),
  mrr: round(rows.reduce((s, r) => s + (r.firstHit ? 1 / r.firstHit : 0), 0) / rows.length),
});

const lines = [
  '# Retrieval comparison: keyword vs semantic `search_notes`',
  '',
  `Generated by \`npm run eval\` in \`harness/vault-mcp\`. Top ${K} distinct notes per question; expected notes are those that hold the answer.`,
  '',
  '| Metric | keyword (before) | semantic (after) |',
  '|---|---|---|',
];
const sums = Object.fromEntries(Object.entries(results).map(([m, rows]) => [m, summary(rows)]));
for (const [metric, label] of [
  ['hitAt1', 'Expected note ranked 1st'],
  ['hitAtK', `Expected note in top ${K}`],
  ['meanRecallAtK', `Mean recall@${K} (share of expected notes found)`],
  ['mrr', 'MRR'],
] as const) {
  lines.push(`| ${label} | ${fmt(sums.keyword![metric], metric)} | ${fmt(sums.semantic![metric], metric)} |`);
}
lines.push('', '## Per question', '');
for (const q of questions) {
  lines.push(`### ${q.id} — ${q.question}`, '', `*${q.kind}*; expected: ${q.expected.map((t) => `\`${t}\``).join(', ')}`, '');
  for (const mode of Object.keys(results)) {
    const row = results[mode]!.find((r) => r.id === q.id)!;
    const top = row.top.length ? row.top.map((t) => (q.expected.includes(t) ? `**${t}**` : t)).join(' · ') : '*(no results)*';
    lines.push(`- ${mode}: ${top} — first hit ${row.firstHit || '—'}, recall ${row.recall}`);
  }
  lines.push('');
}

await writeFile(path.join(DOCS, 'retrieval-results.md'), lines.join('\n'));
await writeFile(path.join(DOCS, 'retrieval-results.json'), `${JSON.stringify({ k: K, summary: sums, results }, null, 2)}\n`);
console.log(JSON.stringify(sums, null, 2));

function round(n: number): number {
  return Math.round(n * 100) / 100;
}

function fmt(value: number, metric: string): string {
  return metric === 'hitAt1' || metric === 'hitAtK' ? `${value} / ${questions.length}` : String(value);
}
