// `npm run eval:planner`: runs the orchestration Planner (.claude/agents/planner.md) on the same task
// with keyword and with semantic search_notes, and saves which vault notes it consulted and the plan.
// Unlike eval:agent, the Planner works in the app repository with its usual tools and guardrails.
import { spawn } from 'node:child_process';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(HERE, '../../..');
const DOCS = path.join(APP_ROOT, 'docs/rag-evaluation');
const SERVER = path.resolve(HERE, '../src/server.ts');
const MODEL = process.env.EVAL_MODEL ?? 'claude-sonnet-5-5';
const TASK =
  'Plan FR-8 Viewing Statistics: an endpoint that returns the number of watched movies, the average rating, ' +
  'and the distribution by genre and by release year. Produce the plan only; do not change anything.';

await Promise.all(['keyword', 'semantic'].map(plan));

async function plan(mode: string): Promise<void> {
  const tmp = await mkdtemp(path.join(tmpdir(), 'vault-planner-'));
  try {
    const mcpConfig = path.join(tmp, 'mcp.json');
    const server = { command: 'node', args: [SERVER], env: { VAULT_SEARCH: mode, VAULT_PUSH: 'false' } };
    await writeFile(mcpConfig, JSON.stringify({ mcpServers: { vault: server } }));
    const started = Date.now();
    const events = await runClaude(APP_ROOT, [
      '-p', TASK,
      '--agent', 'planner',
      '--model', MODEL,
      '--strict-mcp-config', '--mcp-config', mcpConfig,
      '--no-session-persistence',
      '--output-format', 'stream-json', '--verbose',
    ]);
    const vaultCalls: string[] = [];
    let otherCalls = 0;
    let result: { result?: string; num_turns?: number; total_cost_usd?: number } = {};
    for (const event of events) {
      if (event.type === 'assistant') {
        for (const part of event.message.content) {
          if (part.type !== 'tool_use') continue;
          if (part.name.startsWith('mcp__vault__')) vaultCalls.push(`\`${part.name.replace('mcp__vault__', '')}\` ${JSON.stringify(part.input)}`);
          else otherCalls++;
        }
      }
      if (event.type === 'result') result = event;
    }
    const report = [
      `# Planner run — ${mode} search_notes`,
      '',
      `Task: ${TASK}`,
      '',
      `Model ${MODEL}; ${result.num_turns ?? 0} turns; ${Math.round((Date.now() - started) / 1000)} s; $${(result.total_cost_usd ?? 0).toFixed(2)}; ` +
        `${vaultCalls.length} vault calls, ${otherCalls} other tool calls. Generated by \`npm run eval:planner\`.`,
      '',
      '## Vault calls',
      '',
      ...vaultCalls.map((c, i) => `${i + 1}. ${c}`),
      '',
      '## Plan',
      '',
      (result.result ?? '').trim(),
      '',
    ];
    await writeFile(path.join(DOCS, `planner-${mode}.md`), report.join('\n'));
    console.log(`${mode}: ${vaultCalls.length} vault calls, ${otherCalls} other calls`);
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

function runClaude(cwd: string, claudeArgs: string[]): Promise<any[]> {
  return new Promise((resolve, reject) => {
    const child = spawn('claude', claudeArgs, { cwd, stdio: ['ignore', 'pipe', 'pipe'] });
    let out = '';
    let err = '';
    child.stdout.on('data', (d) => (out += d));
    child.stderr.on('data', (d) => (err += d));
    child.on('error', reject);
    child.on('close', (code) => {
      if (code !== 0) return reject(new Error(`claude exited with ${code}: ${err.slice(-500)}`));
      resolve(out.split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l)));
    });
  });
}
